export const getSystemById = (id: string): StarSystem =>
  ALL_STAR_SYSTEMS.find(s => s.id === id) ?? ALL_STAR_SYSTEMS[0];

// Flat list of all bodies across all systems for global lookup
export const ALL_SYSTEM_BODIES = ALL_STAR_SYSTEMS.flatMap(s =>
  s.bodies.flatMap(b => b.children ? [b, ...b.children] : [b])
);

export const getAnyBodyById = (id: string, systemBodies?: CelestialBody[]) => {
  if (systemBodies) {
    const found = systemBodies.flatMap(b => b.children ? [b, ...b.children] : [b]).find(b => b.id === id);
    if (found) return found;
  }
  return ALL_SYSTEM_BODIES.find(b => b.id === id);
};
