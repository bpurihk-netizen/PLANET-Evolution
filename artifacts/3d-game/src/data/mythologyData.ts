/** Get mythology data by constellation id */
export function getMythologyData(id: string): MythologyEntry | undefined {
  return MYTHOLOGY_DATA.find(e => e.id === id);
}

/** Get all entries for a given origin */
export function getMythologyByOrigin(origin: MythologyOrigin): MythologyEntry[] {
  return MYTHOLOGY_DATA.filter(e => e.origin === origin);
}
